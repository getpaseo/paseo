import esbuild from "esbuild";
import { writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const directory = new URL("./", import.meta.url);
async function bundle(name, define = {}) {
  const result = await esbuild.build({
    entryPoints: [fileURLToPath(new URL(name, directory))],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["ios15", "chrome100"],
    minify: true,
    define,
  });
  return result.outputFiles[0].text;
}
const worker = await bundle("worker.ts");
const frame = (await bundle("frame.ts", { ARTIFACT_WORKER: JSON.stringify(worker) })).replace(
  /<\/script/gi,
  "<\\/script",
);
const hash = createHash("sha256").update(frame).digest("base64");
const html = `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-${hash}' 'wasm-unsafe-eval'; worker-src blob:; style-src 'unsafe-inline'; img-src data:; font-src 'none'; connect-src 'none'; frame-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{font-family:system-ui;margin:12px;color-scheme:light dark}*{box-sizing:border-box;max-width:100%}</style></head><body><div id="visual"></div><script type="application/json" id="config">__PASEO_ARTIFACT_CONFIG__</script><script>${frame}</script></body></html>`;
await writeFile(
  new URL("html.gen.ts", directory),
  `// Generated by runtime/build.mjs. Do not edit.\nexport const artifactRuntimeHtml = ${JSON.stringify(html)};\n`,
);
