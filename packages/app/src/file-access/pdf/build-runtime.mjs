import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const directory = path.dirname(fileURLToPath(import.meta.url));
const pdfRoot = path.dirname(fileURLToPath(import.meta.resolve("pdfjs-dist/package.json")));
async function resources(folder, extension) {
  const names = (await fs.readdir(path.join(pdfRoot, folder))).filter((name) =>
    extension.test(name),
  );
  return Object.fromEntries(
    await Promise.all(
      names.map(async (name) => [
        folder === "cmaps" ? name.replace(/\.bcmap$/, "") : name,
        (await fs.readFile(path.join(pdfRoot, folder, name))).toString("base64"),
      ]),
    ),
  );
}
const assets = {
  maps: await resources("cmaps", /\.bcmap$/),
  fonts: await resources("standard_fonts", /\.(ttf|pfb)$/),
};
const result = await esbuild.build({
  entryPoints: [path.join(directory, "runtime/entry.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "chrome120",
  minify: true,
  define: { PASEO_PDF_RESOURCES: JSON.stringify(assets) },
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const notices = (
  await Promise.all(
    [
      "LICENSE",
      "cmaps/LICENSE",
      "standard_fonts/LICENSE_FOXIT",
      "standard_fonts/LICENSE_LIBERATION",
    ].map(async (name) => `${name}\n${await fs.readFile(path.join(pdfRoot, name), "utf8")}`),
  )
)
  .concat(
    `core-js (included in PDF.js legacy build)\n${await fs.readFile(path.resolve(directory, "../../../../../docs/third-party/pdfjs/LICENSE_CORE_JS"), "utf8")}`,
  )
  .join("\n\n")
  .replace(/-->/g, "-- >");
const html = `<!doctype html><html><head><!-- Bundled PDF.js and font licenses: ${notices} --><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src blob: file:; img-src data: blob:; font-src data: blob:; worker-src 'none'; base-uri 'none'; form-action 'none'"><style>
*{box-sizing:border-box}body{margin:0;background:var(--background);color:var(--foreground);font:14px system-ui}header{position:sticky;top:0;padding:8px;background:var(--background);border-bottom:1px solid var(--border);display:flex;gap:6px;align-items:center;flex-wrap:wrap;z-index:2}button,input{font:inherit;color:inherit;background:var(--background);border:1px solid var(--border);border-radius:6px;padding:6px}button{cursor:pointer}#page{width:56px}#search{width:130px}form{display:inline-flex;gap:4px}main{padding:12px;overflow:auto;text-align:center}canvas{background:white;box-shadow:0 2px 8px #0002}#error{padding:8px;white-space:pre-wrap}[hidden]{display:none!important}
</style></head><body><header><button id="previous" aria-label="Previous page">‹</button><input id="page" type="number" min="1" aria-label="Page"><button id="next" aria-label="Next page">›</button><span id="status"></span><button id="zoom-out" aria-label="Zoom out">−</button><button id="zoom-in" aria-label="Zoom in">+</button><form id="search-form"><input id="search" type="search" aria-label="Search"><button type="submit">⌕</button></form></header><div id="error" role="alert"></div><form id="password-form" hidden><input id="password" type="password" autocomplete="off"><button type="submit">OK</button></form><main><canvas></canvas></main><script>${js}</script></body></html>`;
await fs.writeFile(
  path.join(directory, "runtime/html.gen.ts"),
  `// Generated by build-runtime.mjs. Includes Apache-2.0 PDF.js.\nexport const pdfRuntimeHtml = ${JSON.stringify(html)};\n`,
);
console.log(`Bundled offline PDF reader (${html.length} bytes)`);
