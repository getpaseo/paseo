export interface UiIconProps {
  size?: number;
  color?: string;
  strokeWidth?: number | string;
  fill?: string;
  absoluteStrokeWidth?: boolean;
  opacity?: number;
  style?: StyleProp<ViewStyle | Omit<TextStyle, "cursor">>;
  testID?: string;
  accessibilityLabel?: string;
}

export type LucideIcon = ForwardRefExoticComponent<UiIconProps>;

function weightFor(props: UiIconProps): IconWeight {
  if (props.fill && props.fill !== "none" && props.fill !== "transparent") return "fill";
  return Number(props.strokeWidth ?? 2) >= 2.5 ? "bold" : "regular";
}

function uiIcon(Icon: ComponentType<IconProps>, name: string): LucideIcon {
  const UiIcon = forwardRef<unknown, UiIconProps>(function UiIcon(props, _ref) {
    const {
      strokeWidth: _strokeWidth,
      fill: _fill,
      absoluteStrokeWidth: _absolute,
      uniProps: _uniProps,
      opacity,
      style,
      ...rest
    } = props as UiIconProps & { uniProps?: unknown };
    return (
      <Icon
        {...rest}
        style={opacity === undefined ? style : [style, { opacity }]}
        weight={weightFor(props)}
      />
    );
  });
  UiIcon.displayName = name;
  return UiIcon;
}

