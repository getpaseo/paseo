type TranslationOverride<T> = {
  [K in keyof T]?: T[K] extends string ? string : TranslationOverride<T[K]>;
};

function mergeTranslations<T>(base: T, overrides: TranslationOverride<T>): T {
  if (typeof base !== "object" || base === null) {
    return (overrides ?? base) as T;
  }

  const merged: Record<string, unknown> = {
    ...(base as Record<string, unknown>),
  };
  for (const [key, overrideValue] of Object.entries(overrides as Record<string, unknown>)) {
    const baseValue = (base as Record<string, unknown>)[key];
    merged[key] =
      typeof baseValue === "object" &&
      baseValue !== null &&
      typeof overrideValue === "object" &&
      overrideValue !== null
        ? mergeTranslations(baseValue, overrideValue as never)
        : overrideValue;
  }

  return merged as T;
}

