import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import ts from "typescript";

const appRoot = path.resolve(import.meta.dirname, "..");
const screenPath = path.join(appRoot, "src/screens/settings-screen.tsx");
const outputPath = path.join(appRoot, "src/screens/settings/settings-search-source.generated.ts");

const sourceExtensions = [".ts", ".tsx"];

function resolveSourcePath(fromPath, moduleName) {
  if (!moduleName.startsWith("@/")) return null;
  const basePath = path.join(appRoot, "src", moduleName.slice(2));
  for (const extension of sourceExtensions) {
    const candidate = `${basePath}${extension}`;
    if (fs.existsSync(candidate)) return candidate;
  }
  return null;
}

function getStringValue(node) {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
    return node.text;
  }
  return null;
}

function getDynamicTranslationPrefix(node) {
  if (!ts.isTemplateExpression(node)) return null;
  const prefix = node.head.text;
  return prefix.endsWith(".") ? prefix.slice(0, -1) : prefix;
}

function collectTranslationKeys(filePath) {
  const source = ts.createSourceFile(
    filePath,
    fs.readFileSync(filePath, "utf8"),
    ts.ScriptTarget.Latest,
    true,
    filePath.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
  const keys = new Set();

  function visit(node) {
    if (ts.isCallExpression(node)) {
      const expression = node.expression;
      const isTranslationCall =
        (ts.isIdentifier(expression) && expression.text === "t") ||
        (ts.isPropertyAccessExpression(expression) && expression.name.text === "t");
      if (isTranslationCall && node.arguments.length > 0) {
        const argument = node.arguments[0];
        const literal = getStringValue(argument) ?? getDynamicTranslationPrefix(argument);
        if (literal) keys.add(literal);
      }
    }
    ts.forEachChild(node, visit);
  }

  visit(source);
  return [...keys].sort();
}

function collectImportedComponents(source) {
  const imports = new Map();
  source.forEachChild((node) => {
    if (!ts.isImportDeclaration(node) || !ts.isStringLiteral(node.moduleSpecifier)) return;
    const modulePath = resolveSourcePath(screenPath, node.moduleSpecifier.text);
    if (!modulePath || !node.importClause?.namedBindings) return;
    if (!ts.isNamedImports(node.importClause.namedBindings)) return;
    for (const element of node.importClause.namedBindings.elements) {
      imports.set(element.name.text, {
        path: modulePath,
      });
    }
  });
  return imports;
}

function collectContentNames(source) {
  const names = new Set();
  function visit(node) {
    if (
      ts.isPropertyAssignment(node) &&
      ts.isIdentifier(node.name) &&
      node.name.text === "Content"
    ) {
      if (ts.isIdentifier(node.initializer)) {
        names.add(node.initializer.text);
      } else if (
        ts.isCallExpression(node.initializer) &&
        ts.isIdentifier(node.initializer.expression) &&
        node.initializer.expression.text === "createSettingsSearchContent" &&
        ts.isIdentifier(node.initializer.arguments[0])
      ) {
        names.add(node.initializer.arguments[0].text);
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  return names;
}

const screenSource = ts.createSourceFile(
  screenPath,
  fs.readFileSync(screenPath, "utf8"),
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TSX,
);
const imports = collectImportedComponents(screenSource);
const contentNames = collectContentNames(screenSource);
const entries = {};

for (const name of [...contentNames].sort()) {
  const imported = imports.get(name);
  if (!imported) throw new Error(`Cannot resolve settings Content import: ${name}`);
  entries[name] = collectTranslationKeys(imported.path);
}

const entryText = Object.entries(entries)
  .map(([name, keys]) => {
    const keyText = keys.map((key) => `    ${JSON.stringify(key)},`).join("\n");
    return `  ${name}: [\n${keyText}\n  ],`;
  })
  .join("\n");
const output = `// Generated by scripts/generate-settings-search-source.mjs.\nexport const SETTINGS_CONTENT_TRANSLATION_KEYS = {\n${entryText}\n} as const;\n`;
fs.writeFileSync(outputPath, output);
execFileSync(path.resolve(appRoot, "../../node_modules/.bin/oxfmt"), [outputPath], {
  stdio: "ignore",
});
