import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDirectory, "..");
const repositoryRoot = path.resolve(appRoot, "../..");
const entry = path.join(appRoot, "src/mermaid/webview/entry.ts");
const output = path.join(appRoot, "src/mermaid/webview/html.ts");

async function resolveTypeScriptPath(basePath) {
  const candidates = [
    basePath,
    `${basePath}.ts`,
    `${basePath}.tsx`,
    path.join(basePath, "index.ts"),
    path.join(basePath, "index.tsx"),
  ];
  for (const candidate of candidates) {
    try {
      const stat = await fs.stat(candidate);
      if (stat.isFile()) return candidate;
    } catch {
      // Continue through the supported source extensions.
    }
  }
  return basePath;
}

const aliasPlugin = {
  name: "paseo-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => ({
      path: await resolveTypeScriptPath(path.join(appRoot, "src", args.path.slice(2))),
    }));
  },
};

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["ios15", "chrome100"],
  minify: true,
  plugins: [aliasPlugin],
  logLevel: "info",
});

const javascript = result.outputFiles[0]?.text;
if (!javascript) {
  throw new Error("Mermaid WebView bundle produced no JavaScript");
}

const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta http-equiv="Content-Security-Policy" content="default-src 'none'; img-src data:; style-src 'unsafe-inline'; script-src 'unsafe-inline'" />
    <meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover" />
    <style>
      html, body, #mermaid-viewport { width: 100%; height: 100%; margin: 0; overflow: hidden; background: transparent; }
      #mermaid-viewport { position: relative; }
      #mermaid-canvas { position: absolute; left: 0; top: 0; transform-origin: 0 0; }
    </style>
  </head>
  <body>
    <script>${javascript}</script>
  </body>
</html>`;

const contents = `// Generated by packages/app/scripts/build-mermaid-webview-html.mjs.
// Do not edit by hand.

export const mermaidWebViewHtml = ${JSON.stringify(html)};
`;

await fs.writeFile(output, contents);
console.log(`Wrote ${path.relative(repositoryRoot, output)} (${html.length} bytes)`);
