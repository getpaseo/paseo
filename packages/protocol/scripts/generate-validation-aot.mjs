import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../..");
const source = resolve(packageRoot, "src/validation/ws-outbound-aot-source.ts");
const output = resolve(packageRoot, "src/generated/validation/ws-outbound.aot.ts");

await mkdir(dirname(output), { recursive: true });

const result = spawnSync(
  process.execPath,
  [
    resolve(repoRoot, "node_modules/zod-aot/dist/cli/index.js"),
    "generate",
    source,
    "--output",
    output,
    "--no-zod-compat",
  ],
  {
    cwd: repoRoot,
    stdio: "inherit",
  },
);

if (result.error) {
  throw result.error;
}

if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

const generated = await readFile(output, "utf8");
function replaceRequired(input, pattern, replacement, description) {
  const next = input.replace(pattern, replacement);
  if (next === input) {
    throw new Error(`Failed to postprocess generated validator: ${description}`);
  }
  return next;
}

const withNoCheck = replaceRequired(
  generated,
  "// AUTO-GENERATED by zod-aot — DO NOT EDIT",
  "// @ts-nocheck\n// AUTO-GENERATED by zod-aot — DO NOT EDIT",
  "missing zod-aot header",
);
const postprocessed = replaceRequired(
  withNoCheck,
  /from\s+["'][^"']*ws-outbound-aot-source(?:\.js)?["']/g,
  'from "../../validation/ws-outbound-aot-runtime-source.js"',
  "missing ws-outbound-aot-source import",
);

await writeFile(output, postprocessed);
