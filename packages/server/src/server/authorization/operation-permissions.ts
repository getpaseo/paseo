export function requiredPermissionForInbound(operation: InboundOperation): PermissionRequirement {
  return INBOUND_PERMISSION[operation];
}

export function requiredPermissionForOutbound(
  message: SessionOutboundMessage,
): PermissionRequirement {
  // The legacy status envelope carries both agent RPC results and daemon configuration.
  if (
    message.type === "status" &&
    (message.payload.status === "agent_created" || message.payload.status === "agent_create_failed")
  )
    return ["workspace.write", "hub.execute"];
  return OUTBOUND_PERMISSION[message.type];
}
