const states = ["run", "ask", "err", "sleep"];
const sizes = { large: 32, small: 16 };
const expectedCounts = { run: 3, ask: 2, err: 2, sleep: 2 };

function assertKnownFrame(frame, n) {
  assert.equal(frame.length, n);
  for (const row of frame) {
    assert.equal(row.length, n);
    for (const cell of row)
      assert.ok(cell === "." || sprites.palette[cell], `Unknown pixel: ${cell}`);
  }
}

function validate() {
  for (const [size, n] of Object.entries(sizes)) {
    assert.deepEqual(Object.keys(sprites[size]), states);
    for (const state of states) {
      const frames = sprites[size][state];
      assert.equal(frames.length, expectedCounts[state]);
      assert.equal(new Set(frames.map(JSON.stringify)).size, frames.length);
      for (const frame of frames) assertKnownFrame(frame, n);
    }
  }
  for (const [key, color] of Object.entries(sprites.palette))
    assert.match(color, /^#[0-9a-f]{6}$/i, key);
  // Badges cannot rescue identical panda poses: compare masks without status marks.
  const mask = (frame, state) =>
    frame.flatMap((row, y) =>
      [...row].map((cell, x) => {
        if (state === "err" && y <= 2 && x >= 6 && x <= 8) return false;
        if (state === "sleep" && (y < 9 || (y < 11 && x >= 8))) return false;
        return cell !== ".";
      }),
    );
  const differences = [];
  for (let a = 0; a < states.length; a++) {
    for (let b = a + 1; b < states.length; b++) {
      let minimum = 256;
      for (const fa of sprites.small[states[a]])
        for (const fb of sprites.small[states[b]]) {
          const ma = mask(fa, states[a]),
            mb = mask(fb, states[b]);
          minimum = Math.min(
            minimum,
            ma.reduce((count, value, i) => count + (value !== mb[i]), 0),
          );
        }
      assert.ok(minimum >= 35, `Silhouettes too similar: ${states[a]} / ${states[b]} (${minimum})`);
      differences.push(`${states[a]}/${states[b]}=${minimum}`);
    }
  }
  return differences.join(", ");
}

