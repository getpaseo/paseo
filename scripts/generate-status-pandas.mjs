function png(width, height, pixels) {
  const raw = Buffer.alloc((width * 3 + 1) * height);
  for (let y = 0; y < height; y++)
    pixels.copy(raw, y * (width * 3 + 1) + 1, y * width * 3, (y + 1) * width * 3);
  const chunk = (type, data) => {
    const tag = Buffer.from(type),
      length = Buffer.alloc(4),
      crc = Buffer.alloc(4);
    length.writeUInt32BE(data.length);
    crc.writeUInt32BE(crc32(Buffer.concat([tag, data])) >>> 0);
    return Buffer.concat([length, tag, data, crc]);
  };
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header[8] = 8;
  header[9] = 2;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

/** Static contact sheet for eyeballing readability; not part of the app build. Behind --preview. */
/** "a"/"r" (light) become "A"/"R" (dark) on the dark contact sheet; every other cell is unchanged. */
function paletteKeyFor(cell, dark) {
  if (dark && cell === "a") return "A";
  if (dark && cell === "r") return "R";
  return cell;
}

function preview(dark) {
  const width = 1360;
  const rows = [
    ["small", 1, false],
    ["small", 1.5, false],
    ["small", 2, false],
    ["small", 4, false],
    ["small", 1, true],
    ["large", 1, false],
    ["large", 2, false],
    ["large", 4, false],
  ];
  const height = 30 + rows.reduce((sum, [size, scale]) => sum + sizes[size] * scale + 30, 0);
  const background = rgb(dark ? "#121110" : "#F0EEE6");
  const ink = rgb(dark ? "#ECE7DC" : "#15140F");
  const pixels = Buffer.alloc(width * height * 3);
  for (let i = 0; i < pixels.length; i += 3) {
    pixels[i] = background[0];
    pixels[i + 1] = background[1];
    pixels[i + 2] = background[2];
  }
  const put = (x, y, color) => {
    assert.ok(x >= 0 && x < width && y >= 0 && y < height);
    const i = (y * width + x) * 3;
    pixels[i] = color[0];
    pixels[i + 1] = color[1];
    pixels[i + 2] = color[2];
  };
  const label = (text, x, y) => {
    [...text].forEach((letter, i) => {
      assert.ok(font[letter], `Missing glyph ${letter}`);
      font[letter].forEach((row, dy) =>
        [...row].forEach((v, dx) => {
          if (v === "1") put(x + i * 4 + dx, y + dy, ink);
        }),
      );
    });
  };
  label("RUN   ASK   ERR   SLEEP", 16, 12);
  let y = 30;
  for (const [size, scale, silhouette] of rows) {
    const n = sizes[size],
      display = n * scale;
    const cellWidth = Math.max(34, display + 12);
    label(
      silhouette ? "MASK 1X" : `${size.toUpperCase()} ${scale === 1.5 ? "24" : `${scale}X`}`,
      12,
      y + 6,
    );
    let i = 0;
    for (const state of states)
      sprites[size][state].forEach((frame, frameIndex) => {
        const x = 100 + i++ * cellWidth;
        for (let py = 0; py < display; py++)
          for (let px = 0; px < display; px++) {
            const cell = frame[Math.floor(py / scale)][Math.floor(px / scale)];
            if (cell === ".") continue;
            if (
              silhouette &&
              state === "err" &&
              Math.floor(py / scale) <= 2 &&
              Math.floor(px / scale) >= 6 &&
              Math.floor(px / scale) <= 8
            )
              continue;
            if (
              silhouette &&
              state === "sleep" &&
              (Math.floor(py / scale) < 9 ||
                (Math.floor(py / scale) < 11 && Math.floor(px / scale) >= 8))
            )
              continue;
            const color = silhouette ? ink : rgb(sprites.palette[paletteKeyFor(cell, dark)]);
            put(x + px, y + py + 4, color);
          }
        label(`${state.toUpperCase()} ${frameIndex + 1}`, x, y + display + 12);
      });
    y += display + 30;
  }
  return png(width, height, pixels);
}

